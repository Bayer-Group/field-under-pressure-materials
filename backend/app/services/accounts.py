# -*- coding: utf-8 -*-
"""Users of the demo API: a login and a password. A mock for switching between users, not real authentication.

Two tables hold them: app.user_account (accounts that own farms that can be edited: generated by scripts/generate_user_accounts.py or
created by POST /register) and app.demo_user (the logins of the example farmers, farmer001 ..., read-only). `authenticate` looks the
login up in the first, then in the second. An unknown login costs the same work as a wrong password (a dummy hash is verified), so
the answer does not tell which logins exist. The pure helpers are shared with scripts/generate_user_accounts.py.
"""
from __future__ import annotations

import re
import secrets
import unicodedata
from typing import Optional

from backend.app.core.security import hash_password, verify_password

MAX_LOGIN = 30
MIN_PASSWORD, MAX_PASSWORD = 4, 100                          # a mock: a short password is allowed
_LOGIN = re.compile(r"^[a-z0-9][a-z0-9._-]{2,29}$")
_DUMMY_HASH = hash_password("not-a-real-password")           # verified when the login is unknown
_PASSWORD_ALPHABET = "abcdefghjkmnpqrstuvwxyz23456789"       # no 0 o 1 l i: the password is read from a file and typed
_POLISH = str.maketrans({"ł": "l", "Ł": "L"})                # NFKD does not decompose these two


def normalize_login(value: str) -> str:
    return value.strip().lower()


def valid_login(value: str) -> bool:
    return bool(_LOGIN.match(normalize_login(value)))


def validate_registration(login: str, password: str) -> Optional[str]:
    """The reason a new login and password are not acceptable, or None."""
    if not valid_login(login):
        return f"the login must be 3 to {MAX_LOGIN} characters: lower-case letters, digits, dot, underscore or hyphen, starting with a letter or a digit"
    if not (MIN_PASSWORD <= len(password) <= MAX_PASSWORD):
        return f"the password must be {MIN_PASSWORD} to {MAX_PASSWORD} characters"
    return None


def owner_for(login: str) -> str:
    """The owner id of the farms of a new account (the owner column is unique, so a clash gives 409 instead of two accounts sharing a farm)."""
    return "u-" + re.sub(r"[._]", "-", normalize_login(login))


def slugify(text: str, sep: str = ".") -> str:
    """ASCII lower-case words joined by `sep`: "Józef Wiśniewski" -> "jozef.wisniewski"."""
    ascii_text = unicodedata.normalize("NFKD", text.translate(_POLISH)).encode("ascii", "ignore").decode()
    return sep.join(re.findall(r"[a-z0-9]+", ascii_text.lower()))


def generate_password(groups: int = 3, size: int = 4) -> str:
    """A random password in readable groups, for example "kuxa-7mqe-9dwp" (12 characters, about 59 bits)."""
    return "-".join("".join(secrets.choice(_PASSWORD_ALPHABET) for _ in range(size)) for _ in range(groups))


def authenticate(con, login: str, password: str) -> Optional[dict]:
    """The user for a login and a password, or None. Returns {kind: "account" | "example", id, owner_id, role, display_name}.
    `con` returns dict rows."""
    ident = login.strip()
    row = con.execute("SELECT login, password_hash, owner_id, role, display_name FROM app.user_account WHERE login = %s",
                      (normalize_login(ident),)).fetchone()
    kind = "account"
    if row is None:
        row = con.execute("SELECT login, password_hash, owner_id, role, display_name FROM app.demo_user WHERE login = %s",
                          (ident,)).fetchone()
        kind = "example"
    ok = verify_password(password, row["password_hash"] if row else _DUMMY_HASH)
    if not (row and ok):
        return None
    return {"kind": kind, "id": row["login"], "owner_id": row["owner_id"], "role": row["role"], "display_name": row["display_name"]}
